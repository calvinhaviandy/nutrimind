-- NutriMind schema for Neon PostgreSQL. Run against the database selected by
-- DATABASE_URL. Statements are safe to repeat on an existing schema.

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS food_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  food_name VARCHAR(255) NOT NULL,
  image_path VARCHAR(512),
  image_data BYTEA,
  image_mime VARCHAR(64),
  caloric_value DOUBLE PRECISION,
  fat DOUBLE PRECISION,
  saturated_fats DOUBLE PRECISION,
  monounsaturated_fats DOUBLE PRECISION,
  polyunsaturated_fats DOUBLE PRECISION,
  carbohydrates DOUBLE PRECISION,
  sugars DOUBLE PRECISION,
  protein DOUBLE PRECISION,
  dietary_fiber DOUBLE PRECISION,
  cholesterol DOUBLE PRECISION,
  sodium DOUBLE PRECISION,
  water DOUBLE PRECISION,
  vitamin_a DOUBLE PRECISION,
  vitamin_b1 DOUBLE PRECISION,
  vitamin_b11 DOUBLE PRECISION,
  vitamin_b12 DOUBLE PRECISION,
  vitamin_b2 DOUBLE PRECISION,
  vitamin_b3 DOUBLE PRECISION,
  vitamin_b5 DOUBLE PRECISION,
  vitamin_b6 DOUBLE PRECISION,
  vitamin_c DOUBLE PRECISION,
  vitamin_d DOUBLE PRECISION,
  vitamin_e DOUBLE PRECISION,
  vitamin_k DOUBLE PRECISION,
  calcium DOUBLE PRECISION,
  copper DOUBLE PRECISION,
  iron DOUBLE PRECISION,
  magnesium DOUBLE PRECISION,
  manganese DOUBLE PRECISION,
  phosphorus DOUBLE PRECISION,
  potassium DOUBLE PRECISION,
  selenium DOUBLE PRECISION,
  zinc DOUBLE PRECISION,
  nutrition_density DOUBLE PRECISION,
  log_date DATE NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_food_logs_user_date ON food_logs (user_id, log_date);

CREATE TABLE IF NOT EXISTS hydration_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  log_date DATE NOT NULL,
  glasses INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT uq_hydration_user_date UNIQUE (user_id, log_date)
);

CREATE TABLE IF NOT EXISTS meal_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  plan_date DATE NOT NULL,
  calories DOUBLE PRECISION NOT NULL DEFAULT 0,
  protein DOUBLE PRECISION NOT NULL DEFAULT 0,
  carbs DOUBLE PRECISION NOT NULL DEFAULT 0,
  fat DOUBLE PRECISION NOT NULL DEFAULT 0,
  CONSTRAINT uq_meal_plans_user_date UNIQUE (user_id, plan_date)
);

CREATE TABLE IF NOT EXISTS meal_plan_meals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id BIGINT NOT NULL REFERENCES meal_plans (id) ON DELETE CASCADE,
  meal_type VARCHAR(32) NOT NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT NOT NULL,
  calories DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_meal_plan_meals_plan ON meal_plan_meals (plan_id);

CREATE TABLE IF NOT EXISTS meal_plan_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meal_id BIGINT NOT NULL REFERENCES meal_plan_meals (id) ON DELETE CASCADE,
  item_name VARCHAR(512) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_meal_plan_items_meal ON meal_plan_items (meal_id);

CREATE TABLE IF NOT EXISTS meal_plan_drafts (
  user_id BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  plan_json TEXT NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
